-- Only the selected stored candidate can become public. Selection is atomic and once-only.
create or replace function public.publish_movie_review(
  p_draft_id uuid, p_selection integer
) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  d public.movie_review_drafts%rowtype;
  new_review_id uuid;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_selection not between 0 and 2 then raise exception 'Invalid candidate selection'; end if;
  select * into d from public.movie_review_drafts
    where id = p_draft_id and user_id = auth.uid() for update;
  if not found then raise exception 'Draft not found'; end if;
  if d.published_at is not null then raise exception 'Already published'; end if;
  if char_length(d.candidates[p_selection + 1]) not between 1 and 160 then
    raise exception 'Invalid one-liner';
  end if;
  insert into public.movie_reviews (draft_id, movie_id, user_id, one_liner, tone)
    values (d.id, d.movie_id, d.user_id, d.candidates[p_selection + 1], d.tone)
    returning id into new_review_id;
  update public.movie_review_drafts set published_at = now() where id = d.id;
  return new_review_id;
end $$;
revoke all on function public.publish_movie_review(uuid, integer) from public;
grant execute on function public.publish_movie_review(uuid, integer) to authenticated;

-- Aggregate counts never expose individual voters.
create or replace function public.movie_review_scores()
returns table (review_id uuid, upvotes bigint, downvotes bigint)
language sql stable security definer set search_path = '' as $$
  select r.id,
    count(v.review_id) filter (where v.value = 1),
    count(v.review_id) filter (where v.value = -1)
  from public.movie_reviews r
  left join public.movie_review_votes v on v.review_id = r.id
  group by r.id;
$$;
revoke all on function public.movie_review_scores() from public;
grant execute on function public.movie_review_scores() to anon, authenticated;

create table if not exists public.movie_generation_usage (
  user_id uuid not null references auth.users(id) on delete cascade,
  day date not null,
  attempts integer not null check (attempts between 1 and 10),
  primary key (user_id, day)
);
alter table public.movie_generation_usage enable row level security;
revoke all on public.movie_generation_usage from anon, authenticated;
create or replace function public.claim_movie_generation_attempt()
returns boolean language plpgsql security definer set search_path = '' as $$
declare used integer; begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  insert into public.movie_generation_usage(user_id, day, attempts)
    values (auth.uid(), (now() at time zone 'America/New_York')::date, 1)
    on conflict (user_id, day) do update
      set attempts = public.movie_generation_usage.attempts + 1
      where public.movie_generation_usage.attempts < 10
    returning attempts into used;
  return used is not null;
end $$;
revoke all on function public.claim_movie_generation_attempt() from public;
grant execute on function public.claim_movie_generation_attempt() to authenticated;

