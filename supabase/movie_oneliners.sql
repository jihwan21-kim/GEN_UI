-- OneLine Cinema: additive, standalone movie tables. Does NOT modify restaurant tables.
-- Run in the SAME Supabase project as the existing app, via SQL Editor.
-- Re-runnable for this app's own policies/functions. Existing restaurant data is preserved.
begin;

create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 120),
  release_year integer not null check (release_year between 1888 and 2100),
  genres text[] not null check (
    cardinality(genres) between 1 and 3
    and genres <@ array[
      'Action','Animation','Comedy','Crime','Documentary','Drama',
      'Fantasy','Horror','Mystery','Romance','Sci-Fi','Thriller'
    ]::text[]
  ),
  poster_path text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint movie_poster_owner_path check (
    poster_path is null or created_by is null or (
      poster_path like created_by::text || '/%'
      and char_length(poster_path) <= 220
    )
  )
);
create unique index if not exists movies_unique_title_year
  on public.movies (lower(trim(title)), release_year);
create index if not exists movies_recent on public.movies (created_at desc);
alter table public.movies enable row level security;
revoke all on public.movies from anon, authenticated;
grant select on public.movies to anon, authenticated;
grant insert (title, release_year, genres, poster_path, created_by) on public.movies to authenticated;
grant update (title, release_year, genres, poster_path) on public.movies to authenticated;
grant delete on public.movies to authenticated;
do $$ declare seq text; begin
  seq := pg_get_serial_sequence('public.movies', 'id');
  if seq is not null then
    execute format('grant usage on sequence %s to authenticated', seq);
  end if;
end $$;
drop policy if exists movies_public_read on public.movies;
drop policy if exists movies_insert_own on public.movies;
drop policy if exists movies_update_own on public.movies;
drop policy if exists movies_delete_own on public.movies;
create policy movies_public_read on public.movies
  for select to anon, authenticated using (true);
create policy movies_insert_own on public.movies
  for insert to authenticated with check (created_by = (select auth.uid()));
create policy movies_update_own on public.movies
  for update to authenticated using (created_by = (select auth.uid()))
  with check (created_by = (select auth.uid()));
create policy movies_delete_own on public.movies
  for delete to authenticated using (created_by = (select auth.uid()));

-- The original long thoughts and all three generated options stay PRIVATE.
